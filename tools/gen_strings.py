"""Genera i file .resx e Strings.cs da tools/strings.py."""
import os
import sys
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(__file__))
from strings import S, LANGS  # noqa: E402

root = os.path.join(os.path.dirname(__file__), "..", "src", "Navigator.Core", "Localization")
os.makedirs(root, exist_ok=True)

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
"""

for i, lang in enumerate(LANGS):
    name = "Strings.resx" if lang == "it" else f"Strings.{lang}.resx"
    with open(os.path.join(root, name), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(HEADER)
        for key in sorted(S):
            value = S[key][i]
            f.write(f'  <data name="{key}" xml:space="preserve"><value>{escape(value)}</value></data>\n')
        f.write("</root>\n")

lines = [
    "// <auto-generated>Generato da tools/gen_strings.py: modificare tools/strings.py, non questo file.</auto-generated>",
    "#nullable enable",
    "using System.Globalization;",
    "using System.Resources;",
    "",
    "namespace Navigator.Core.Localization;",
    "",
    "/// <summary>Testi dell'interfaccia nella lingua corrente (italiano, inglese, tedesco, francese, spagnolo).</summary>",
    "public static class Strings",
    "{",
    '    private static readonly ResourceManager Resources = new("Navigator.Core.Localization.Strings", typeof(Strings).Assembly);',
    "",
    "    /// <summary>Lingua dei testi; null = lingua dell'interfaccia del thread corrente.</summary>",
    "    public static CultureInfo? Culture { get; set; }",
    "",
    "    /// <summary>Codici delle lingue disponibili (\"it\", \"en\", ...).</summary>",
    "    public static IReadOnlyList<string> Languages { get; } = [" + ", ".join(f'"{l}"' for l in LANGS) + "];",
    "",
    "    public static string Get(string key) => Resources.GetString(key, Culture) ?? key;",
    "",
    "    /// <summary>Testo con segnaposto {0}, {1}... formattato secondo la lingua corrente.</summary>",
    "    public static string Format(string template, params object?[] args) =>",
    "        string.Format(Culture ?? CultureInfo.CurrentCulture, template, args);",
    "",
]
for key in sorted(S):
    it = S[key][0].replace("\n", " ").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    lines.append(f"    /// <summary>{it}</summary>")
    lines.append(f"    public static string {key} => Get(nameof({key}));")
    lines.append("")
lines[-1] = "}"
with open(os.path.join(root, "Strings.cs"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(S)} testi in {len(LANGS)} lingue")
